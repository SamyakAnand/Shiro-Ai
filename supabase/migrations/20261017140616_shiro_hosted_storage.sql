create table public.repositories (
  id text primary key,
  name text not null,
  url text not null,
  branch text not null,
  commit_sha text not null,
  status text not null check (status in ('indexing', 'ready', 'failed')),
  error text,
  created_at timestamptz not null,
  updated_at timestamptz not null,
  owner_id uuid not null references auth.users(id) on delete cascade
);

create table public.files (
  id bigint generated by default as identity primary key,
  repo_id text not null references public.repositories(id) on delete cascade,
  path text not null,
  language text not null,
  content text not null,
  sha256 text not null,
  unique (repo_id, path)
);

create table public.symbols (
  id bigint generated by default as identity primary key,
  repo_id text not null references public.repositories(id) on delete cascade,
  path text not null,
  name text not null,
  kind text not null,
  line integer not null check (line > 0),
  unique (repo_id, path, name, line)
);

create table public.edges (
  id bigint generated by default as identity primary key,
  repo_id text not null references public.repositories(id) on delete cascade,
  source text not null,
  target text not null,
  kind text not null,
  unique (repo_id, source, target, kind)
);

create table public.investigations (
  id text primary key,
  repo_id text not null references public.repositories(id) on delete cascade,
  title text not null,
  question text not null,
  result text not null,
  created_at timestamptz not null
);

create table public.artifacts (
  id text primary key,
  repo_id text not null references public.repositories(id) on delete cascade,
  commit_sha text not null,
  type text not null check (type in ('report', 'flashcards', 'quiz')),
  title text not null,
  focus text not null,
  payload text not null,
  created_at timestamptz not null
);

create index files_repo_path on public.files (repo_id, path);
create index symbols_repo_name on public.symbols (repo_id, lower(name));
create index edges_repo_source on public.edges (repo_id, source);
create index investigations_repo_created on public.investigations (repo_id, created_at desc);
create index artifacts_repo_created on public.artifacts (repo_id, created_at desc);

