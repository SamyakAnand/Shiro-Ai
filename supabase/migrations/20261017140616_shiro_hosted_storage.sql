create policy repositories_owner on public.repositories
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy files_owner on public.files
  for all to authenticated
  using (exists (select 1 from public.repositories r where r.id = repo_id and r.owner_id = (select auth.uid())))
  with check (exists (select 1 from public.repositories r where r.id = repo_id and r.owner_id = (select auth.uid())));

